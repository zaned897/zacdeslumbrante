const KB_STORAGE_KEY = 'zacatecas_knowledge_base_v1';

export function getStoredKnowledgeBase(): KnowledgeBaseURL[] {
  try {
    const raw = localStorage.getItem(KB_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(KB_STORAGE_KEY, JSON.stringify(INITIAL_KNOWLEDGE_BASE));
      return INITIAL_KNOWLEDGE_BASE;
    }
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
  } catch (err) {
    console.error('Failed to load knowledge base from localStorage:', err);
  }
  return INITIAL_KNOWLEDGE_BASE;
}

export function saveStoredKnowledgeBase(list: KnowledgeBaseURL[]): void {
  try {
    localStorage.setItem(KB_STORAGE_KEY, JSON.stringify(list));
  } catch (err) {
    console.error('Failed to save knowledge base:', err);
  }
}

export function resetKnowledgeBase(): KnowledgeBaseURL[] {
  try {
    localStorage.setItem(KB_STORAGE_KEY, JSON.stringify(INITIAL_KNOWLEDGE_BASE));
  } catch (err) {
    console.error('Failed to reset knowledge base:', err);
  }
  return INITIAL_KNOWLEDGE_BASE;
}
